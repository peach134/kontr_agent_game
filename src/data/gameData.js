export const FINAL_RANKS = [
  { min: 20, max: 25, title: 'Стажёр службы безопасности' },
  { min: 26, max: 33, title: 'Младший риск-аналитик' },
  { min: 34, max: 38, title: 'Комплаенс-специалист' },
  { min: 39, max: 40, title: 'Налоговый Шерлок' },
];

const allowedAnswers = ANSWER_OPTIONS.map((option) => option.label);

export function validateGameData() {
  return {
    hasFourRounds: ROUNDS.length === 4,
    roundQuestionCounts: ROUNDS.map((round) => ({
      roundId: round.id,
      count: round.questions.length,
      valid: round.questions.length === 10,
    })),
    invalidAnswers: ROUNDS.flatMap((round) =>
      round.questions
        .filter((question) => !allowedAnswers.includes(question.correctAnswer))
        .map((question) => ({
          roundId: round.id,
          questionId: question.id,
          correctAnswer: question.correctAnswer,
        })),
    ),
  };
}
